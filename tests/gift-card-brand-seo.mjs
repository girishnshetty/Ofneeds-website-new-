// Read-only HTTP verification of every brand page. No enquiries or messages sent.
import assert from 'node:assert/strict';
import { loadTypescript } from './helpers/load-typescript.mjs';
const { giftBrands, giftBrandSeo } = await loadTypescript('src/lib/gift-card-brands.ts');
const base = process.argv[2] || 'http://127.0.0.1:5174';
assert.ok(['127.0.0.1','localhost'].includes(new URL(base).hostname));
const origin = 'https://www.ofneeds.com';
const decode = value => value.replace(/&amp;/g,'&').replace(/&quot;/g,'"').replace(/&#39;|&apos;/g,"'").replace(/&lt;/g,'<').replace(/&gt;/g,'>');
const sitemap = await (await fetch(base+'/sitemap.xml')).text();
const catalogue = await (await fetch(base+'/gift-cards')).text();
const catalogueLinks = new Set([...catalogue.matchAll(/<a\b[^>]*href="([^"]+)"/g)].map(match => new URL(decode(match[1]), base+'/gift-cards').pathname));
let checked = 0;
async function check(brand) {
	const response = await fetch(base+brand.href);
	assert.equal(response.status,200,brand.href);
	const html = await response.text();
	const profile = giftBrandSeo(brand);
	assert.equal(decode(html.match(/<title>(.*?)<\/title>/s)[1]),profile.title);
	assert.equal([...html.matchAll(/<h1\b/g)].length,1);
	assert.ok(html.includes('rel="canonical" href="'+origin+brand.href+'"'));
	assert.ok(html.includes('content="index, follow, max-image-preview:large"'));
	assert.ok(sitemap.includes('<loc>'+origin+brand.href+'</loc><lastmod>2026-10-29</lastmod>'));
	assert.ok(catalogueLinks.has(brand.href),brand.href+' discoverable through a normal link');
	const text = decode(html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g,'').replace(/<[^>]+>/g,' ')).replace(/\s+/g,' ');
	const schemas = [...html.matchAll(/<script type="application\/ld\+json">(.*?)<\/script>/gs)].flatMap(match=>JSON.parse(match[1])['@graph']);
	const breadcrumbs = schemas.find(schema=>schema['@type']==='BreadcrumbList');
	assert.deepEqual(breadcrumbs.itemListElement.map(item=>item.item),[origin+'/',origin+'/gift-cards',origin+brand.href]);
	const service = schemas.find(schema=>schema['@type']==='Service');
	assert.equal(service.name,profile.service);
	assert.equal(service.provider['@id'],origin+'/#organization');
	assert.ok(!schemas.some(schema=>['Offer','AggregateRating'].includes(schema['@type'])));
	const faqs = schemas.find(schema=>schema['@type']==='FAQPage');
	assert.equal(faqs.mainEntity.length,profile.faqs.length);
	for(const faq of profile.faqs) assert.ok(text.includes(faq.question) && text.includes(faq.answer),brand.href+' visible FAQ parity');
	assert.ok(html.includes(brand.logo.src));
	const requirementLink = [...html.matchAll(/<a\b[^>]*href="([^"#]+giftBrief[^\"]+)"/g)][0];
	assert.ok(requirementLink,brand.href+' has an actionable quotation link in SSR HTML');
	const enquiry = new URL(decode(requirementLink[1]),base+brand.href);
	assert.equal(enquiry.pathname,'/contact');
	assert.equal(enquiry.searchParams.get('giftQuantity'),'100');
	assert.ok(enquiry.searchParams.get('giftBrief').includes(brand.options[0].name));
	checked++;
}
for(let index=0;index<giftBrands.length;index+=6) await Promise.all(giftBrands.slice(index,index+6).map(check));
const invalid = await fetch(base+'/gift-cards/not-a-real-brand');
assert.equal(invalid.status,404);
assert.ok((await invalid.text()).includes('noindex, follow'));
const tracked = await (await fetch(base+'/gift-cards/starbucks?utm_source=test')).text();
assert.ok(tracked.includes('rel="canonical" href="'+origin+'/gift-cards/starbucks"'));
console.log(JSON.stringify({brandPages:checked,coveredListings:giftBrands.reduce((sum,brand)=>sum+brand.options.length,0),checks:'metadata, canonical, sitemap, links, breadcrumbs, actual logos, FAQ parity, enquiry handoff and 404',result:'passed'},null,2));
